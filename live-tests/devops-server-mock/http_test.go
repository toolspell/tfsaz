func TestCollectionURLs(t *testing.T) {
	mockProject := &project{ID: "project-id", Name: "Mock Project"}
	mockRepo := &repo{ID: "repo-id", Name: "web app", Project: mockProject}
	coll := &collection{Name: "DefaultCollection", Projects: []*project{mockProject}, Repos: []*repo{mockRepo}}
	s := &server{cfg: config{sshPort: "2222", pat: "test"}, collections: []*collection{coll}, viewer: &identity{}}
	for _, tc := range []struct {
		name, origin, virtualDir, sshHost string
	}{
		{"HTTP", "http://devops.mock.test:8080", "", "devops.mock.test"},
		{"HTTPS", "https://devops.mock.test", "", "devops.mock.test"},
		{"HTTPS with virtual directory", "https://other.mock.test:8443", "/tfs", "other.mock.test"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			base := tc.origin + tc.virtualDir + "/DefaultCollection"
			target := base + "/_apis?allHostTypes=true"
			r := httptest.NewRequest(http.MethodOptions, target, nil)
			r.SetBasicAuth("", s.cfg.pat)
			response := httptest.NewRecorder()
			s.ServeHTTP(response, r)
			if response.Code != http.StatusOK || response.Header().Get("Content-Location") != target || !bytes.Equal(response.Body.Bytes(), catalog) {
				t.Fatalf("catalog status = %d, Content-Location = %q; want 200, %q and the recorded catalog", response.Code, response.Header().Get("Content-Location"), target)
			}
			dir, _ := splitCollectionPath(r.URL.Path)
			links := s.links(r, dir, coll)
			if got, want := links.api("_apis", "Identities", "id"), base+"/_apis/Identities/id"; got != want {
				t.Errorf("identity URL = %q; want %q", got, want)
			}
			if got, want := links.gitWeb(mockRepo), base+"/Mock%20Project/_git/web%20app"; got != want {
				t.Errorf("clone URL = %q; want %q", got, want)
			}
			if got, want := links.gitSSH(mockRepo), "ssh://"+tc.sshHost+":2222"+tc.virtualDir+"/DefaultCollection/Mock%20Project/_git/web%20app"; got != want {
				t.Errorf("SSH clone URL = %q; want %q", got, want)
			} else if s.repoForSSHPath(tc.virtualDir+"/DefaultCollection/Mock%20Project/_git/web%20app") != mockRepo {
				t.Error("SSH lookup did not find the repository")
			}

			target = base + "/_apis/connectionData?api-version=5.0-preview.1"
			r = httptest.NewRequest(http.MethodGet, target, nil)
			r.SetBasicAuth("", s.cfg.pat)
			response = httptest.NewRecorder()
			s.ServeHTTP(response, r)
			var data struct{ WebApplicationRelativeDirectory string }
			if err := json.Unmarshal(response.Body.Bytes(), &data); err != nil {
				t.Fatal(err)
			}
			wantDir := strings.TrimPrefix(tc.virtualDir+"/DefaultCollection/", "/")
			if response.Code != http.StatusOK || response.Header().Get("Content-Location") != target || data.WebApplicationRelativeDirectory != wantDir {
				t.Errorf("connection data status = %d, Content-Location = %q, relative directory = %q; want 200, %q, %q",
					response.Code, response.Header().Get("Content-Location"), data.WebApplicationRelativeDirectory, target, wantDir)
			}
		})
	}
}

func TestTextGenerator(t *testing.T) {
	s := &server{cfg: config{pat: "mock-pat"}}
	call := func(method, path, body string) *httptest.ResponseRecorder {
		r := httptest.NewRequest(method, "http://llm.mock.test"+path, strings.NewReader(body))
		response := httptest.NewRecorder()
		s.serveLLM(response, r)
		return response
	}
	t.Run("completion", func(t *testing.T) {
		for _, auth := range []string{"", "Bearer anything"} {
			r := httptest.NewRequest(http.MethodPost, "http://llm.mock.test/v1/chat/completions",
				strings.NewReader(`{"model":"live-test","messages":[{"role":"user","content":"Write a PR title"}]}`))
			if auth != "" {
				r.Header.Set("Authorization", auth)
			}
			response := httptest.NewRecorder()
			s.serveLLM(response, r)
			var got struct {
				Object  string
				Model   string
				Choices []struct {
					Index   int
					Message struct{ Role, Content string }
					Finish  string `json:"finish_reason"`
				}
			}
			if err := json.Unmarshal(response.Body.Bytes(), &got); err != nil || response.Code != http.StatusOK {
				t.Fatalf("status = %d, body = %s, err = %v; want 200 and JSON", response.Code, response.Body, err)
			}
			if got.Object != "chat.completion" || got.Model != "live-test" || len(got.Choices) != 1 ||
				got.Choices[0].Index != 0 || got.Choices[0].Message.Role != "assistant" || got.Choices[0].Finish != "stop" {
				t.Fatalf("completion = %+v; want one assistant choice that stopped, model live-test", got)
			}
			var content map[string]string
			if err := json.Unmarshal([]byte(got.Choices[0].Message.Content), &content); err != nil {
				t.Fatal(err)
			}
			want := map[string]string{
				"title": "Live test pull request", "body": "Generated by the live-test text generator.",
				"subject": "Live test commit", "branch": "live-test-branch",
			}
			for k, v := range want {
				if content[k] != v {
					t.Errorf("content[%q] = %q; want %q", k, content[k], v)
				}
			}
		}
	})
	t.Run("echoes the model", func(t *testing.T) {
		response := call(http.MethodPost, "/v1/chat/completions", `{"model":"other-model"}`)
		if !strings.Contains(response.Body.String(), `"model":"other-model"`) {
			t.Errorf("body = %s; want model other-model", response.Body)
		}
	})
	t.Run("models", func(t *testing.T) {
		response := call(http.MethodGet, "/v1/models", "")
		var got struct{ Data []struct{ ID, Name string } }
		if err := json.Unmarshal(response.Body.Bytes(), &got); err != nil || response.Code != http.StatusOK ||
			len(got.Data) != 1 || got.Data[0].ID != "live-test" || got.Data[0].Name == "" {
			t.Errorf("status = %d, body = %s, err = %v; want 200 and the live-test model", response.Code, response.Body, err)
		}
	})
	t.Run("bad body", func(t *testing.T) {
		response := call(http.MethodPost, "/v1/chat/completions", `not json`)
		var got struct {
			Error struct{ Message, Type string }
		}
		if err := json.Unmarshal(response.Body.Bytes(), &got); err != nil || response.Code != http.StatusBadRequest ||
			got.Error.Type != "invalid_request_error" || got.Error.Message == "" {
			t.Errorf("status = %d, body = %s, err = %v; want 400 in OpenAI's error shape", response.Code, response.Body, err)
		}
	})
	t.Run("other path", func(t *testing.T) {
		for _, path := range []string{"/", "/v1/embeddings", "/chat/completions"} {
			if response := call(http.MethodPost, path, `{}`); response.Code != http.StatusNotFound {
				t.Errorf("POST %s = %d; want 404", path, response.Code)
			}
		}
		if response := call(http.MethodGet, "/v1/chat/completions", ""); response.Code != http.StatusNotFound {
			t.Errorf("GET completions = %d; want 404", response.Code)
		}
	})
	t.Run("journal", func(t *testing.T) {
		entries := s.journal.requests("")
		if len(entries) == 0 {
			t.Fatal("journal is empty")
		}
		first := entries[0]
		if first.Method != http.MethodPost || first.Path != "/v1/chat/completions" || first.Host != "llm.mock.test" ||
			first.Scheme != "http" || first.Status != http.StatusOK || first.AuthScheme != "" {
			t.Errorf("first entry = %+v; want the unauthenticated completion", first)
		}
		if entries[1].AuthScheme != "Bearer" {
			t.Errorf("second entry auth scheme = %q; want Bearer", entries[1].AuthScheme)
		}
		if last := entries[len(entries)-1]; last.Status != http.StatusNotFound {
			t.Errorf("last entry status = %d; want 404", last.Status)
		}
	})
}
