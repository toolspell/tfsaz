package main

import (
	"encoding/json"
	"io"
	"net/http"
	"time"
)

// llmReply holds every key T3's prompts ask for (PR content, commit message
// with branch, branch name, thread title). T3 takes the first JSON object in
// the completion text and reads the keys it needs.
const llmReply = `{"title":"Live test pull request","body":"Generated by the live-test text generator.","subject":"Live test commit","branch":"live-test-branch"}`

// serveLLM is the OpenAI-compatible text generator T3 can be pointed at
// (baseUrl http://llm.mock.test/v1). T3 sends no stream or schema options and
// treats redirects as errors.
func (s *server) serveLLM(w http.ResponseWriter, r *http.Request) {
	s.journaled(w, r, func(w http.ResponseWriter, r *http.Request) {
		switch {
		case r.Method == http.MethodPost && r.URL.Path == "/v1/chat/completions":
			var request struct {
				Model string `json:"model"`
			}
			body, err := io.ReadAll(http.MaxBytesReader(w, r.Body, 4<<20))
			if err == nil {
				err = json.Unmarshal(body, &request)
			}
			if err != nil {
				llmJSON(w, http.StatusBadRequest, map[string]any{"error": map[string]any{
					"message": "The request body is not valid JSON.", "type": "invalid_request_error",
				}})
				return
			}
			llmJSON(w, http.StatusOK, map[string]any{
				"id": "chatcmpl-live-test", "object": "chat.completion", "created": time.Now().Unix(),
				"model": request.Model,
				"choices": []any{map[string]any{
					"index":         0,
					"message":       map[string]any{"role": "assistant", "content": llmReply},
					"finish_reason": "stop",
				}},
			})
		case r.Method == http.MethodGet && r.URL.Path == "/v1/models":
			llmJSON(w, http.StatusOK, map[string]any{"object": "list", "data": []any{
				map[string]any{"id": "live-test", "name": "Live test", "object": "model", "owned_by": "live-test"},
			}})
		default:
			notFound(w)
		}
	})
}

func llmJSON(w http.ResponseWriter, status int, v any) {
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(status)
	_ = json.NewEncoder(w).Encode(v)
}
